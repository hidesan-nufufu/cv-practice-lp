/* =============================================================================
 * config.js  ―― ここだけ書き換えれば計測が動きます
 * =============================================================================
 *
 *  【このファイルは広告計測のどの部分？】
 *  LP（あなたのサイト）が「どの計測ツールに、どのIDでデータを送るか」を決める設定です。
 *  広告 → LP → GTM → GA4 / 広告媒体  の "LP → GTM" のつなぎ目にあたります。
 *
 *  ─────────────────────────────────────────────────────────────
 *  MODE の説明（練習の進め方）
 *  ─────────────────────────────────────────────────────────────
 *   'off'    : 何も外部に送らない。dataLayer への push だけ行う。
 *              → まず画面右下のデバッグパネルで「イベントが発生していること」を確認する段階。
 *              → GTM のアカウントがまだ無くても練習できます。ここから始めてOK。
 *
 *   'gtm'    : GTM のスニペットだけを読み込む（★実務ではこれが標準）。
 *              GA4 も Google広告も Meta Pixel も、タグは全部 GTM の中で管理します。
 *              → GTM_ID を自分のコンテナIDに書き換えてください。
 *
 *   'direct' : GTM を使わず、LP から直接 GA4(gtag.js) と Meta Pixel を読み込む。
 *              → 「GTM を挟まないと何が起きるか」を体感するための比較用モードです。
 *              → GTM とは併用しないでください（同じイベントが二重に飛びます）。
 * ============================================================================= */

